#!/usr/bin/env python3
"""Rasterise the launcher's Tabler line icons into 42x42 alpha masks.

Source SVGs live in tools/icon_src/tabler/ (Tabler Icons, MIT licence —
see the LICENSE file there; https://tabler.io/icons). Each is rendered
white-on-transparent at GLYPH px and centred in a 42x42 cell; only the
alpha channel is kept. The launcher tints the masks at start-up
(launcher.cpp::_icon_list_init), so one mask serves both the idle look
(accent glyph on a dark disc) and the selected look (dark glyph on an
accent disc), antialiased against the right background either way.

    python tools/gen_tabler_icons.py            # writes launcher_glyphs.h
    python tools/gen_tabler_icons.py --preview out.png

Needs: pip install pillow resvg-py
"""
import io
import os
import sys

import resvg_py
from PIL import Image

W = H = 42
GLYPH = 28          # rendered icon size inside the 42px cell
STROKE = 2.0        # Tabler's native weight at 24px; scales with GLYPH

# Launcher order (must match icon_pic_list / ICON_NUM in
# launcher_render_callback.hpp): name in C -> source file.
ICONS = [
    ("watch",      "clock.svg"),
    ("volume",     "volume.svg"),
    ("timer",      "hourglass-high.svg"),
    ("stopwatch",  "stopwatch.svg"),
    ("pomodoro",   "brain.svg"),
    ("brightness", "sun.svg"),
    ("claude",     "asterisk.svg"),
    ("pcstats",    "cpu.svg"),
    ("more",       "dots.svg"),
]

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "icon_src", "tabler")
OUT = os.path.normpath(os.path.join(HERE, "..", "src", "apps", "launcher",
                                    "launcher_icons", "launcher_glyphs.h"))


def render(path):
    svg = open(path, encoding="utf-8").read()
    svg = svg.replace("currentColor", "#ffffff")
    svg = svg.replace('stroke-width="2"', f'stroke-width="{STROKE}"')
    png = resvg_py.svg_to_bytes(svg_string=svg, width=GLYPH, height=GLYPH)
    glyph = Image.open(io.BytesIO(bytes(png))).convert("RGBA")
    cell = Image.new("RGBA", (W, H), (0, 0, 0, 0))
    off = (W - GLYPH) // 2
    cell.paste(glyph, (off, off), glyph)
    return cell.getchannel("A")


def emit(masks):
    lines = [
        "/**",
        " * @file launcher_glyphs.h",
        " * @brief 42x42 alpha masks for the launcher icons. GENERATED by",
        " *        tools/gen_tabler_icons.py from Tabler Icons (MIT licence,",
        " *        https://tabler.io/icons) — edit the script, not this file.",
        " */",
        "#pragma once",
        "#include <stdint.h>",
        "",
    ]
    for name, mask in masks:
        data = list(mask.tobytes())
        lines.append(f"static const uint8_t launcher_glyph_{name}[{W * H}] = {{")
        for row in range(H):
            vals = ", ".join(f"{v:3d}" for v in data[row * W:(row + 1) * W])
            lines.append(f"    {vals},")
        lines.append("};")
        lines.append("")
    return "\n".join(lines)


def preview(masks, path):
    """Idle and selected looks side by side, 4x, to eyeball the set."""
    colors = [(0, 240, 255), (255, 42, 109), (252, 238, 10), (0, 255, 159),
              (255, 0, 60), (255, 158, 0), (217, 119, 87), (0, 240, 255),
              (58, 107, 140)]
    bg = (7, 11, 18)
    sheet = Image.new("RGB", (len(masks) * 50, 100), bg)
    for i, (_, mask) in enumerate(masks):
        col = colors[i % len(colors)]
        for row, (disc, ink) in enumerate([(tuple(int(c * .18 + b * .82) for c, b in zip(col, bg)), col),
                                           (col, bg)]):
            cell = Image.new("RGB", (W, H), bg)
            discm = Image.new("L", (W, H), 0)
            from PIL import ImageDraw
            ImageDraw.Draw(discm).ellipse((0, 0, W - 1, H - 1), fill=255)
            cell.paste(Image.new("RGB", (W, H), disc), (0, 0), discm)
            cell.paste(Image.new("RGB", (W, H), ink), (0, 0), mask)
            sheet.paste(cell, (i * 50 + 4, row * 50 + 4))
    sheet.resize((sheet.width * 3, sheet.height * 3), Image.NEAREST).save(path)
    print("preview", path)


def main():
    masks = [(name, render(os.path.join(SRC, f))) for name, f in ICONS]
    if len(sys.argv) > 2 and sys.argv[1] == "--preview":
        preview(masks, sys.argv[2])
        return
    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(emit(masks))
    print("wrote", OUT)


if __name__ == "__main__":
    main()
